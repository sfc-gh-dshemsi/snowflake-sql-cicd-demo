#!/usr/bin/env python3
"""Build the standalone Snowsight worksheet, without connecting to Snowflake."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GUARD = """    IF (CURRENT_ORGANIZATION_NAME() <> 'SFSENORTHAMERICA'
        OR CURRENT_ACCOUNT_NAME() <> 'DSHEMSI_AWS1'
        OR CURRENT_USER() <> 'DSHEMSI') THEN
        RAISE wrong_target;
    END IF;
"""


def guarded(body):
    return ("EXECUTE IMMEDIATE $$\nDECLARE\n"
            "    wrong_target EXCEPTION (-20001, 'STOP: expected SFSENORTHAMERICA-DSHEMSI_AWS1 / DSHEMSI');\n"
            "BEGIN\n" + GUARD + body + "\nEND;\n$$;\n")


def render(text):
    for key, value in {"database": "DEV_DB", "bronze": "BRONZE"}.items():
        text = text.replace(f"<% {key} %>", value)
    return text


def build():
    sections = ["""-- GENERATED by scripts/build_setup.py. Edit canonical sources, then regenerate.
-- MANUAL SNOWSIGHT SETUP ONLY. Not part of any deployment workflow.
-- Run each EXECUTE IMMEDIATE block as a whole; stop on ANY error.
-- No block bypasses its own account/user guard. DDL is NOT transactionally rolled back.
-- Preflight: verify existing objects belong to this demo before rerunning.
SELECT CURRENT_ORGANIZATION_NAME(), CURRENT_ACCOUNT_NAME(), CURRENT_USER(), CURRENT_ROLE();
SHOW DATABASES LIKE 'DEV_DB';
SHOW DATABASES LIKE 'QA_DB';
SHOW DATABASES LIKE 'PROD_DB';
SHOW WAREHOUSES LIKE 'RETAIL_CICD_WH';
SHOW ROLES LIKE 'RETAIL_%';

-- 1. Role administration (SECURITYADMIN). Roles are isolated siblings.
USE ROLE SECURITYADMIN;
USE SECONDARY ROLES NONE;
"""]
    roles = []
    for environment in ("PR", "DEV", "QA", "PROD"):
        role = f"RETAIL_{environment}_DEPLOY"
        roles.extend([
            f"    CREATE ROLE IF NOT EXISTS {role};",
            f"    GRANT ROLE {role} TO ROLE SYSADMIN;",
            f"    GRANT ROLE {role} TO USER DSHEMSI;",
        ])
    sections.append(guarded("\n".join(roles)))
    sections.append("\n-- 2. Infrastructure (SYSADMIN). No CI role owns a database or schema.\nUSE ROLE SYSADMIN;\n")
    infrastructure = ["""    CREATE WAREHOUSE IF NOT EXISTS RETAIL_CICD_WH
        WAREHOUSE_SIZE = 'XSMALL'
        AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
        STATEMENT_TIMEOUT_IN_SECONDS = 300
        COMMENT = 'Retail SQL CI/CD demo';"""]
    for environment in ("DEV", "QA", "PROD"):
        database = f"{environment}_DB"
        infrastructure.append(f"    CREATE DATABASE IF NOT EXISTS {database};")
        for layer in ("BRONZE", "SILVER", "GOLD"):
            infrastructure.append(f"    CREATE SCHEMA IF NOT EXISTS {database}.{layer} WITH MANAGED ACCESS;")
    for layer in ("BRONZE", "SILVER", "GOLD"):
        infrastructure.append(f"    CREATE SCHEMA IF NOT EXISTS DEV_DB.CI_{layer} WITH MANAGED ACCESS;")
    for environment in ("PR", "DEV", "QA", "PROD"):
        role = f"RETAIL_{environment}_DEPLOY"
        database = "DEV_DB" if environment == "PR" else f"{environment}_DB"
        prefix = "CI_" if environment == "PR" else ""
        infrastructure.extend([
            f"    GRANT USAGE ON WAREHOUSE RETAIL_CICD_WH TO ROLE {role};",
            f"    GRANT USAGE ON DATABASE {database} TO ROLE {role};",
        ])
        for layer, privileges in (
            ("BRONZE", "USAGE, CREATE TABLE"),
            ("SILVER", "USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE PROCEDURE, CREATE TASK"),
            ("GOLD", "USAGE, CREATE VIEW"),
        ):
            infrastructure.append(f"    GRANT {privileges} ON SCHEMA {database}.{prefix}{layer} TO ROLE {role};")
    sections.append(guarded("\n".join(infrastructure)))
    sections.append("""
-- No EXECUTE TASK grant: CI creates/updates a suspended task and calls the procedure directly.
-- 3. DEV input tables and rows, owned by the same role used by Actions.
USE ROLE RETAIL_DEV_DEPLOY;
USE WAREHOUSE RETAIL_CICD_WH;
USE DATABASE DEV_DB;
USE SCHEMA BRONZE;
""")
    sources = [ROOT / "sql/10_raw_tables.sql", ROOT / "sql/20_seed.sql"]
    sections.append(guarded("\n".join(render(path.read_text()) for path in sources)))
    sections.append("""
-- 4. Visible data: fresh setup expects 4 customers and 11 orders.
SELECT * FROM DEV_DB.BRONZE.CUSTOMERS ORDER BY CUSTOMER_ID;
SELECT * FROM DEV_DB.BRONZE.ORDERS ORDER BY ORDER_ID;
-- Relationship illustration: order 107 intentionally has no matching customer.
SELECT orders.ORDER_ID, orders.CUSTOMER_ID, customers.CUSTOMER_NAME,
       orders.ORDER_AMOUNT, orders.ORDER_STATUS
FROM DEV_DB.BRONZE.ORDERS AS orders
LEFT JOIN DEV_DB.BRONZE.CUSTOMERS AS customers
  ON orders.CUSTOMER_ID = customers.CUSTOMER_ID
ORDER BY orders.ORDER_ID;
SHOW GRANTS TO ROLE RETAIL_PR_DEPLOY;
SHOW GRANTS TO ROLE RETAIL_DEV_DEPLOY;
SHOW GRANTS TO ROLE RETAIL_QA_DEPLOY;
SHOW GRANTS TO ROLE RETAIL_PROD_DEPLOY;
-- QA/PROD have empty schemas. GitHub Actions creates their business objects first.
""")
    return "".join(sections)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "setup.sql"
    expected = build()
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit("setup.sql is stale; run python3 scripts/build_setup.py")
        print("PASS: generated setup.sql matches canonical sources")
    else:
        output.write_text(expected)
        print(f"Generated {output}; no Snowflake connection was made")
