#!/usr/bin/env python3
"""Generate a plain-SQL Snowsight setup file; never connect to Snowflake."""
import argparse
from pathlib import Path
from textwrap import dedent

ROOT = Path(__file__).resolve().parents[1]
ENVIRONMENTS = ('PR', 'DEV', 'QA', 'PROD')


def section(number, title):
    return f"\n-- {'=' * 76}\n-- {number}. {title}\n-- {'=' * 76}\n"


def render(text):
    for key, value in {'database': 'DEV_DB', 'bronze': 'BRONZE'}.items():
        text = text.replace(f'<% {key} %>', value)
    return text


def admin_statements(filename, first_statement):
    """Copy a known component's static DDL, excluding its procedural guard."""
    text = (ROOT / filename).read_text()
    start = text.index('    ' + first_statement)
    end = text.index('\nEND;\n$$;', start)
    return dedent(text[start:end]) + '\n'


def build():
    sections = ["""-- ============================================================================
-- Retail SQL CI/CD Demo - All-in-One Snowsight Setup
-- ============================================================================
-- Copy this file into Snowsight. No other file is needed to execute it.
-- Intended account: SFSENORTHAMERICA-DSHEMSI_AWS1.
-- Repository: sfc-gh-dshemsi/snowflake-sql-cicd-demo.
-- Read section 1 before running setup and section 6 before policy attachment.
-- This is plain SQL: checks display results; they do NOT automatically stop writes.
-- Stop on any error. The final status is not proof that earlier statements succeeded.
-- Only reuse existing objects if they belong exclusively to this demo.
-- Existing data and configuration are not replaced or automatically reconciled.
-- PROD is created disabled; this script never enables it or changes an existing user's disabled state.
-- Generated by scripts/build_setup.py; edit its sources before regenerating.

USE ROLE ACCOUNTADMIN;
USE SECONDARY ROLES NONE;
SET USERNAME = (SELECT CURRENT_USER());
ALTER SESSION SET QUERY_TAG = 'retail-sql-cicd-demo:manual-setup';
"""]
    sections.append(section(1, 'Confirm the Account and Existing Objects'))
    sections.append("""SELECT CURRENT_ORGANIZATION_NAME() AS ORGANIZATION,
       CURRENT_ACCOUNT_NAME() AS ACCOUNT,
       $USERNAME AS SETUP_USER;
-- Confirm the account above is the intended demo account before continuing.
SHOW DATABASES LIKE 'DEV_DB';
SHOW DATABASES LIKE 'QA_DB';
SHOW DATABASES LIKE 'PROD_DB';
SHOW WAREHOUSES LIKE 'RETAIL_CICD_WH';
SHOW ROLES LIKE 'RETAIL_%';
SHOW USERS LIKE 'RETAIL_%_SVC';
SHOW PARAMETERS LIKE 'NETWORK_POLICY' IN ACCOUNT;
-- If an account policy exists, ask the administrator to review section 6 first.
""")
    sections.append(section(2, 'Create Deployment Roles'))
    sections.append('USE ROLE SECURITYADMIN;\n')
    for environment in ENVIRONMENTS:
        role = f'RETAIL_{environment}_DEPLOY'
        sections.append(f'CREATE ROLE IF NOT EXISTS {role};\n'
                        f'GRANT ROLE {role} TO ROLE SYSADMIN;\n'
                        f'GRANT ROLE {role} TO USER IDENTIFIER($USERNAME);\n\n')
    sections.append(section(3, 'Create Warehouse, Databases, and Schemas'))
    sections.append("""USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS RETAIL_CICD_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    STATEMENT_TIMEOUT_IN_SECONDS = 300
    COMMENT = 'Retail SQL CI/CD demo';
""")
    for environment in ('DEV', 'QA', 'PROD'):
        sections.append(f'\nCREATE DATABASE IF NOT EXISTS {environment}_DB;\n')
        for layer in ('BRONZE', 'SILVER', 'GOLD'):
            sections.append(f'CREATE SCHEMA IF NOT EXISTS {environment}_DB.{layer} WITH MANAGED ACCESS;\n')
    sections.append('\n-- Separate schemas for pull-request validation.\n')
    for layer in ('BRONZE', 'SILVER', 'GOLD'):
        sections.append(f'CREATE SCHEMA IF NOT EXISTS DEV_DB.CI_{layer} WITH MANAGED ACCESS;\n')
    sections.append(section(4, 'Grant Each Role Access to Its Environment'))
    for environment in ENVIRONMENTS:
        role = f'RETAIL_{environment}_DEPLOY'
        database = 'DEV_DB' if environment == 'PR' else f'{environment}_DB'
        prefix = 'CI_' if environment == 'PR' else ''
        sections.append(f'-- {environment}\nGRANT USAGE ON WAREHOUSE RETAIL_CICD_WH TO ROLE {role};\n'
                        f'GRANT USAGE ON DATABASE {database} TO ROLE {role};\n')
        for layer, privileges in (
            ('BRONZE', 'USAGE, CREATE TABLE'),
            ('SILVER', 'USAGE, CREATE TABLE, CREATE VIEW, CREATE FUNCTION, CREATE PROCEDURE, CREATE TASK'),
            ('GOLD', 'USAGE, CREATE VIEW'),
        ):
            sections.append(f'GRANT {privileges} ON SCHEMA {database}.{prefix}{layer} TO ROLE {role};\n')
        sections.append('\n')
    sections.append('-- No EXECUTE TASK grant: deployment tests call the procedure directly.\n')
    sections.append(section(5, 'Create GitHub Actions OIDC Users'))
    sections.append('USE ROLE ACCOUNTADMIN;\n'
                    '-- Existing users are preserved; inspect their identity settings and grants on reruns.\n'
                    '-- The subjects below are specific to this repository.\n')
    sections.append(admin_statements('oidc_setup.sql', 'CREATE USER IF NOT EXISTS'))
    sections.append(section(6, 'Create and Attach the GitHub Runner Network Policy'))
    sections.append("""-- Review these results BEFORE running the ALTER USER statements below.
-- A user policy can override the account policy; it is not an additive exception.
-- If a different policy is present, STOP and obtain administrator review.
-- Do not overwrite an existing policy assignment without that review.
SHOW PARAMETERS LIKE 'NETWORK_POLICY' IN ACCOUNT;
""")
    for environment in ENVIRONMENTS:
        sections.append(f"SHOW PARAMETERS LIKE 'NETWORK_POLICY' FOR USER RETAIL_{environment}_SVC;\n")
    sections.append("""
CREATE NETWORK POLICY IF NOT EXISTS RETAIL_GITHUB_RUNNERS
    ALLOWED_NETWORK_RULE_LIST = (
        'SNOWFLAKE.NETWORK_SECURITY.GITHUBACTIONS_GLOBAL'
    )
    BLOCKED_NETWORK_RULE_LIST = ()
    COMMENT = 'Retail demo GitHub Actions runners';

-- If the policy already exists, creation above leaves its contents unchanged.
-- Review the allowed and blocked lists before attaching it.
DESC NETWORK POLICY RETAIL_GITHUB_RUNNERS;

-- Attach ONLY to automation users. Never attach this policy to the human login or account.
""")
    for environment in ENVIRONMENTS:
        sections.append(f'ALTER USER RETAIL_{environment}_SVC\n'
                        '    SET NETWORK_POLICY = RETAIL_GITHUB_RUNNERS;\n')
    sections.append(section(7, 'Create the Snowsight Git Integration'))
    sections.append(admin_statements('git_setup.sql', 'CREATE API INTEGRATION IF NOT EXISTS'))
    sections.append('-- Interactive GitHub sign-in is completed in Snowsight after setup.\n')
    sections.append(section(8, 'Create DEV Tables and Insert Sample Rows'))
    sections.append("""-- Use the same owner role as the DEV Actions deployment.
USE ROLE RETAIL_DEV_DEPLOY;
USE WAREHOUSE RETAIL_CICD_WH;
USE DATABASE DEV_DB;
USE SCHEMA BRONZE;

""")
    for filename in ('sql/10_raw_tables.sql', 'sql/20_seed.sql'):
        sections.append(render((ROOT / filename).read_text()) + '\n')
    sections.append(section(9, 'Verify the Sample Data and Configuration'))
    sections.append("""-- Fresh setup expects 4 customers and 11 orders.
SELECT * FROM DEV_DB.BRONZE.CUSTOMERS ORDER BY CUSTOMER_ID;
SELECT * FROM DEV_DB.BRONZE.ORDERS ORDER BY ORDER_ID;
SELECT orders.ORDER_ID, orders.CUSTOMER_ID, customers.CUSTOMER_NAME,
       orders.ORDER_AMOUNT, orders.ORDER_STATUS
FROM DEV_DB.BRONZE.ORDERS AS orders
LEFT JOIN DEV_DB.BRONZE.CUSTOMERS AS customers
  ON orders.CUSTOMER_ID = customers.CUSTOMER_ID
ORDER BY orders.ORDER_ID;

USE ROLE ACCOUNTADMIN;
""")
    for environment in ENVIRONMENTS:
        sections.append(f'DESC USER RETAIL_{environment}_SVC;\n'
                        f'SHOW GRANTS TO USER RETAIL_{environment}_SVC;\n'
                        f'SHOW GRANTS TO ROLE RETAIL_{environment}_DEPLOY;\n'
                        f"SHOW PARAMETERS LIKE 'NETWORK_POLICY' FOR USER RETAIL_{environment}_SVC;\n")
    sections.append("""SHOW GRANTS TO ROLE PUBLIC;
DESC API INTEGRATION RETAIL_GITHUB_APP;
USE ROLE RETAIL_DEV_DEPLOY;

-- Inspect every statement result; only treat setup as complete if none failed.
SELECT 'Setup script finished - confirm all statements succeeded' AS STATUS;

-- Next: complete Snowsight Git sign-in and GitHub environment approvals (README steps 3-4).
-- Keep PROD disabled until its required-reviewer gate is configured and verified.
-- QA/PROD business objects are deployed by Actions, not by this setup file.
-- Documentation:
-- https://docs.snowflake.com/en/sql-reference/session-variables
-- https://docs.snowflake.com/en/user-guide/network-policies
-- https://docs.snowflake.com/en/developer-guide/snowflake-cli/cicd/github-action
-- https://docs.snowflake.com/en/sql-reference/sql/create-api-integration
""")
    return ''.join(sections)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'setup.sql'
    expected = build()
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit('setup.sql is stale; run python3 scripts/build_setup.py')
        print('PASS: generated setup.sql matches canonical sources')
    else:
        output.write_text(expected)
        print(f'Generated {output}; no Snowflake connection was made')
